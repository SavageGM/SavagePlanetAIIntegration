import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {extractActor} from '../scripts/extract.mjs';
import {executeReadOperation} from '../scripts/actor-operations.mjs';
const source=process.argv[2];if(!source)throw new Error('Provide Belladonna exported Foundry actor JSON');
const doc=JSON.parse(readFileSync(source,'utf8'));const data=extractActor(doc);
assert.equal(data.identity.name,'Belladonna Marshall');
for(const [attr,expected] of Object.entries({ST:9,DX:11,IQ:14,HT:12,WILL:19,PER:14}))assert.equal(data.attributes[attr].imported,expected,attr);
const actor={id:data.identity.id,name:doc.name,type:doc.type,system:doc.system,toObject(){return doc;}};
const game={user:{isGM:true},system:{id:'gurps',version:'0.18.27'},actors:{get:id=>id===actor.id?actor:null,contents:[actor]}};
const summary=executeReadOperation(game,'getActor',{actorId:actor.id});
assert.equal(summary.attributes.ST.display,9);assert.equal(summary.pointTotal,300);
assert.equal(executeReadOperation(game,'listActors',{}).actors[0].id,actor.id);
assert.ok(executeReadOperation(game,'getSkills',{actorId:actor.id}).skills.length>0);
assert.equal(executeReadOperation(game,'getAttacks',{actorId:actor.id}).attacks.melee.length,3);
assert.ok(executeReadOperation(game,'getHitLocations',{actorId:actor.id}).hitLocations.length>0);
assert.throws(()=>executeReadOperation({...game,user:{isGM:false}},'listActors',{}),/GM/);
assert.throws(()=>executeReadOperation(game,'updateActor',{}),/forbidden/);
console.log('PASS: Belladonna v0.2 operation regression');
