import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {extractActor,validateActor} from '../scripts/extract.mjs';
const belladonna=JSON.parse(readFileSync(process.argv[2],'utf8'));
const gia=JSON.parse(readFileSync(process.argv[3],'utf8'));
const offline=extractActor(belladonna);
assert.equal(offline.identity.name,'Belladonna Marshall');
assert.equal(offline.attributes.ST.imported,9);
assert.equal(offline.attributes.ST.stored,10);
assert.equal(offline.attributes.ST.display,9);
assert.equal(offline.attributes.IQ.imported,14);
assert.equal(offline.attributes.WILL.imported,19);
assert.equal(offline.pointTotal,300);
assert.equal(offline.provenance.exportedWithGGA,'0.18.27');
assert.equal(offline.provenance.documentGGA,'0.18.17');
assert.equal(validateActor(offline).find(x=>x.name==='Live effective attributes').status,'info');
const prepared=structuredClone(belladonna.system);
for(const a of Object.values(prepared.attributes))a.value=a.import;
for(const s of Object.values(prepared.skills))s.level=s.import;
const live=extractActor(belladonna,prepared,'0.18.27');
assert.equal(live.attributes.ST.effective,9);
assert.equal(live.attributes.IQ.display,14);
assert.equal(live.skills.find(x=>x.name==='Computer Operation/TL9').levelSource,'prepared');
assert.equal(validateActor(live).find(x=>x.name==='Live effective attributes').status,'pass');
const other=extractActor(gia);
assert.equal(other.identity.name,'Gia Segarra');
assert.equal(other.attributes.ST.imported,12);
assert.equal(other.skills.find(x=>x.name==='Tracking').level,20);
assert.equal(other.attacks.melee.length,3);
assert.equal(other.hitLocations.find(x=>x.name==='Skull').dr,2);
console.log('PASS: Belladonna + Gia regression tests');
